using Xunit;

// 测试类之间不并行（2026-09-07）。
//
// 病根：十几个仓储测试类在 Dispose 里调 SqliteConnection.ClearAllPools()，那是个**全局**操作——
// 清的是整个进程的连接池，包括别的测试类此刻正在用的连接。并行跑的时候，A 类收尾会偶发地
// 掐掉 B 类的连接，于是 B 类里某个跟它八竿子打不着的断言莫名其妙失败一次，重跑又好了。
// 实测就撞到过一次：【抓板块列表不会抹掉层级】在全量里失败，单独跑和再跑全量都过。
//
// 这种偶发失败最坏的地方不是浪费时间，是**会让人不信任测试结果**——真出了问题也当成抖动。
// 代价：全量从 12 秒变成 ~30 秒，换回确定性，划算。
[assembly: CollectionBehavior(DisableTestParallelization = true)]
