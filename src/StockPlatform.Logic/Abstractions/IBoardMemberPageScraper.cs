namespace StockPlatform.Logic.Abstractions;

/// <summary>
/// 用**真实浏览器操作行情中心的板块页**来取成分股（2026-09-05）——不是我们自己拼 URL 发请求，
/// 而是打开页面、点表头、点页码，把页面**自己**发出去的那些请求的响应截下来。
///
/// ════ 为什么要这一条路 ════
/// 2026-09-05 在同一台机器、同一时刻实测出来的差别：
///
/// | 方式                                   | 结果 |
/// |---------------------------------------|------|
/// | 浏览器地址栏直接导航到接口 URL             | **503**（页面显示 didn't send any data） |
/// | 打开板块页、点页码，让页面自己发那个请求      | **200**，数据正常 |
///
/// 两者的 IP、浏览器、Cookie 全一样，差别只在**请求的形状**：页面发的是 JSONP
/// （<c>&lt;script src&gt;</c>，带 <c>cb=</c> 回调、带 Referer、Sec-Fetch-Dest 是 script），
/// 而导航发的是 document 请求。服务端认这个。
///
/// 所以这条路的原则是：**页面自己怎么行为就怎么行为，我们只管操作它**。
/// 它顺带还打一次 push2 的资金流小表也好、<c>pz</c> 被锁死在 20 也好，都不去干预——
/// 一改就不是"页面自己发的请求"了，而那正是唯一能拿到 200 的东西。
///
/// ════ 代价，以及为什么认了 ════
/// <c>pz=20</c> 而不是我们自己拼 URL 时的 100，加上每翻一页页面还会附带打一次 push2，
/// 全量一轮从约 1300 个请求涨到约 4800 个。认这个代价是因为：**通不了的话请求再少也没用**，
/// 而时间上装得下——收市后开跑，按人翻页的节奏串行走完约 4~5 小时，第二天早上 8 点前收工。
///
/// ⚠ 有一件事必须靠点表头解决：页面默认按 <c>fid=f3</c>（涨跌幅）排序，那个盘中一直在变，
/// 翻页会跨页重复和遗漏（实测 141 只的板块抓成 138 只）。**点一下表头「代码」列**，
/// 页面自己就会改用 <c>fid=f12</c> 重新请求——排序键唯一且不变，翻页才是安全的。
///
/// 实现是 <c>ChromeCdpBoardPageScraper</c>（Data 层）——启动一个真的 Chrome/Edge，
/// 用 CDP 驱动它。原来试过用嵌在程序里的 WebView2，但 2026-09-06 实测：同一时刻同一个 IP，
/// WebView2 里那张成分股表**渲染不出来**（表头和分页控件都不存在），
/// 而真浏览器（哪怕是全新未登录的 profile）正常。
/// </summary>
public interface IBoardMemberPageScraper
{
    /// <summary>
    /// 抓取过程中要让人知道的事：弹了图片验证、等了多久、这一页没回来在重试……
    /// **必须转发到程序的运行日志里**——这条通道要无人值守跑一整夜，
    /// 人第二天早上唯一能复盘的就是日志（2026-09-06：一开始接到 Debug.WriteLine 上，
    /// 等于验证提示和频率统计全丢了）。
    /// </summary>
    event Action<string>? OnStatus;

    /// <summary>浏览器起来了没。false＝这台机器上用不了，调用方该退回别的通道。</summary>
    bool IsReady { get; }

    /// <summary>建浏览器、打开东财页面拿 Cookie。**要在开抓之前调一次**，别把那几秒混进第一个板块。</summary>
    Task<bool> EnsureReadyAsync(CancellationToken ct = default);

    /// <summary>
    /// 抓一个板块的成分股：打开它的板块页 → 点表头「代码」→ 逐页点页码，
    /// 把页面自己发出去的那些请求的响应收集起来。
    /// </summary>
    /// <returns>
    /// 去重后的代码名单，以及**接口自报的 total**。total 交给上游对账用——
    /// 差一只都说明名单不完整，宁可整轮重来也不能把半截名单写进库
    /// （上游是快照语义，"这轮没返回的＝已下架"会连成分股一起删）。
    /// total 为 0 表示页面没给出总数，上游据此判断"这个板块是空的"还是"没取到"。
    /// </returns>
    Task<(IReadOnlyList<string> Codes, int Total)> ScrapeMembersAsync(
        string boardCode, CancellationToken ct = default);

    /// <summary>
    /// 抓取期间把浏览器窗口开着，让人实时看见东财那边在发生什么——数据在刷、
    /// 弹了图片验证码、还是页面打不开。摆在角落、不抢焦点，嫌碍事可以直接关。
    /// </summary>
    Task ShowWorkWindowAsync(CancellationToken ct = default);
}
